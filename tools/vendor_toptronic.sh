#!/usr/bin/env bash
# Regenerate esphome/components/toptronic from upstream + local patches.
#
#   tools/vendor_toptronic.sh          # rewrite the vendored copy
#   tools/vendor_toptronic.sh --check  # verify the vendored copy is exactly upstream@REF + patches (CI)
#
# To update upstream: change REF, run the script, `make check && make compile`,
# and fix/drop patches that no longer apply (see patches/toptronic/).
set -euo pipefail

UPSTREAM_URL="https://github.com/nliaudat/esp_canbus"
REF="02744916c6b5c4396ef72c3267b17f3b6818ab10"
SUBDIR="esphome/components/toptronic"

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
DEST="$ROOT/esphome/components/toptronic"
PATCHES="$ROOT/patches/toptronic"

work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

git -C "$work" init -q src
git -C "$work/src" remote add origin "$UPSTREAM_URL"
git -C "$work/src" fetch -q --depth 1 origin "$REF"
git -C "$work/src" checkout -q FETCH_HEAD

out="$work/toptronic"
cp -r "$work/src/$SUBDIR" "$out"
for p in "$PATCHES"/*.patch; do
  git -C "$out" apply --whitespace=nowarn "$p"
done
cat > "$out/VENDORED.md" <<EOF
# Vendored component — do not edit by hand

Generated by \`tools/vendor_toptronic.sh\` from
$UPSTREAM_URL/tree/$REF/$SUBDIR (Apache-2.0)
with the patches in \`patches/toptronic/\` applied.
EOF

if [[ "${1:-}" == "--check" ]]; then
  if diff -r -x __pycache__ "$out" "$DEST" >/dev/null; then
    echo "vendored toptronic: OK (upstream ${REF:0:7} + $(ls "$PATCHES"/*.patch | wc -l) patch(es))"
  else
    echo "vendored toptronic differs from upstream ${REF:0:7} + patches:" >&2
    diff -r -x __pycache__ "$out" "$DEST" | head -20 >&2
    echo "run tools/vendor_toptronic.sh (never edit esphome/components/toptronic by hand)" >&2
    exit 1
  fi
else
  rm -rf "$DEST"
  mkdir -p "$(dirname "$DEST")"
  cp -r "$out" "$DEST"
  echo "vendored toptronic from ${REF:0:7} into ${DEST#"$ROOT"/}"
fi
